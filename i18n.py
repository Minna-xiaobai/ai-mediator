def translate(key: str, lang: str, **params) -> str:
    entry = STRINGS[key]
    text = entry.get(lang) or entry[DEFAULT_LANGUAGE]
    return text.format(**params) if params else text


def language_from_locale(locale: str | None) -> str:
    """Map a browser locale (zh-TW, ja-JP, en-US…) to a supported language, else English."""
    prefix = (locale or "").lower()[:2]
    return prefix if prefix in LANGUAGES else DEFAULT_LANGUAGE
